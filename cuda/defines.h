#pragma once

#include <cuda_runtime.h>
#include <cstdio>

/*################################################################################################################################################################################*/
#define cudaCheckError(err) \
    do \
    { \
        if ((err) != cudaSuccess) \
        { \
            const auto errStr = cudaGetErrorString(err); \
            fprintf(stderr, "[%d] %s at {%s:%d}\n", err, errStr, __FILE__, __LINE__); \
            fflush(stderr); \
            fflush(stdout); \
            exit(13); \
        } \
    } \
    while(0)

